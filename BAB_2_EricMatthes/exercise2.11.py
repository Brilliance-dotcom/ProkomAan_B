Name = "\thussain\n"
print(Name)
print(Name.lstrip())
print(Name.rstrip())
print(Name.strip())
#about :
#this program is to show how to use the lstrip(), rstrip(), and strip() methods in Python. The lstrip() method removes any leading whitespace characters from the string, the rstrip() method removes any trailing whitespace characters, and the strip() method removes both leading and trailing whitespace characters.   

